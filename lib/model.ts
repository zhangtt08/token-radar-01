// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// other rankable pre-token protocol below the floor: the early rows the radar exists to find. A protocol
// is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown at the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, and it is priced the way a market prices
// a token: by comparables. For each category, the multiple is the median market-cap-to-TVL ratio of the
// protocols in that category whose token already trades, shrunk toward the global median when the
// category has few live names, and clamped to a sane band. A pre-token protocol's implied value is its
// TVL times its category's multiple, times a growth factor from its seven-day TVL change, times a
// maturity factor from how long it has run with no token. No protocol name is ever special-cased: the
// same function scores every row, and the dashboard prints the category multiples it used.
//
//   multiple(cat) = shrink(median live mcap/tvl in cat, global median), clamped to [0.05, 1.5]
//   base          = tvl_usd x multiple(cat)
//   growth        = clamp(change_7d, -60, 120) per cent
//   growthMult    = 1 + (growth / 100) x 0.5
//   maturity      = 0.5 + min(age_days, 1095) / 1095 x 0.5   (age_days unknown: 365)
//   implied       = max(1, round(base x growthMult x maturity))

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

